/**
 * Intelligent semantic article search engine with hidden tags, synonym expansion, and relevance scoring.
 */
export function searchArticles(articles: ArticleItem[], rawQuery: string): ArticleItem[] {
  if (!rawQuery || rawQuery.trim().length === 0) {
    return articles;
  }

  const cleanQuery = rawQuery.toLowerCase().trim();
  const queryTokens = cleanQuery.split(/[\s,.;:!?\-\/]+/).filter(t => t.length > 0);

  if (queryTokens.length === 0) return articles;

  // Build expanded search tokens including synonyms
  const expandedTokens = new Set<string>();
  queryTokens.forEach(token => {
    expandedTokens.add(token);
    
    // Direct synonym lookup
    if (SYNONYM_MAP[token]) {
      SYNONYM_MAP[token].forEach(syn => expandedTokens.add(syn.toLowerCase()));
    }

    // Stem / prefix lookup
    Object.keys(SYNONYM_MAP).forEach(stem => {
      if (token.startsWith(stem) || stem.startsWith(token)) {
        SYNONYM_MAP[stem].forEach(syn => expandedTokens.add(syn.toLowerCase()));
      }
    });
  });

  const expandedList = Array.from(expandedTokens);

  // Score articles
  const scored = articles.map(article => {
    let score = 0;
    const title = (article.title || '').toLowerCase();
    const excerpt = (article.excerpt || '').toLowerCase();
    const path = (article.path || '').toLowerCase();
    const category = (article.category || '').toLowerCase();
    const content = (article.content || '').toLowerCase();
    
    // Retrieve semantic hidden tags for this article
    const staticTags = ARTICLE_SEMANTIC_TAGS[article.path] || [];
    const customTags = (article.tags || []).map(t => t.toLowerCase());
    const allTags = [...staticTags, ...customTags].map(t => t.toLowerCase());

    // 1. Direct query matching
    if (title === cleanQuery) score += 100;
    else if (title.includes(cleanQuery)) score += 50;

    if (allTags.some(t => t === cleanQuery)) score += 60;
    else if (allTags.some(t => t.includes(cleanQuery))) score += 40;

    if (excerpt.includes(cleanQuery)) score += 25;
    if (path.includes(cleanQuery)) score += 20;
    if (category.includes(cleanQuery)) score += 15;
    if (content && content.includes(cleanQuery)) score += 15;

    // 2. Expanded tokens matching
    for (const token of expandedList) {
      if (token.length < 2) continue;

      if (title.includes(token)) score += 30;
      
      const tagMatch = allTags.some(t => t.includes(token) || token.includes(t));
      if (tagMatch) score += 35;

      if (excerpt.includes(token)) score += 15;
      if (path.includes(token)) score += 10;
      if (category.includes(token)) score += 8;
    }

    return { article, score };
  });

  // Filter only items with score > 0 and sort by highest score first
  return scored
    .filter(item => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .map(item => item.article);
}
